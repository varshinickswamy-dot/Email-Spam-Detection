def consume_rate_limit(database_path, bucket_key, limit, window_seconds, now):
    now_text = now.isoformat(timespec="seconds")
    cutoff = (now - timedelta(seconds=window_seconds)).isoformat(timespec="seconds")
    with _connect(database_path) as connection:
        connection.execute(
            """
            INSERT INTO rate_limit_buckets (bucket_key, attempts, window_started_at)
            VALUES (?, 1, ?)
            ON CONFLICT(bucket_key) DO UPDATE SET
                attempts = CASE
                    WHEN rate_limit_buckets.window_started_at <= ? THEN 1
                    ELSE rate_limit_buckets.attempts + 1
                END,
                window_started_at = CASE
                    WHEN rate_limit_buckets.window_started_at <= ?
                    THEN excluded.window_started_at
                    ELSE rate_limit_buckets.window_started_at
                END
            """,
            (bucket_key, now_text, cutoff, cutoff),
        )
        row = connection.execute(
            "SELECT attempts, window_started_at FROM rate_limit_buckets "
            "WHERE bucket_key = ?",
            (bucket_key,),
        ).fetchone()
    window_started = datetime.fromisoformat(row["window_started_at"])
    retry_after = max(
        1,
        int((window_started.timestamp() + window_seconds) - now.timestamp()),
    )
    return row["attempts"] <= limit, retry_after, row["attempts"]


def prune_expired_data(database_path, history_cutoff, token_cutoff, rate_limit_cutoff):
    with _connect(database_path) as connection:
        connection.execute(
            "DELETE FROM predictions WHERE created_at < ?", (history_cutoff,)
        )
        connection.execute(
            """
            DELETE FROM scan_batches
            WHERE NOT EXISTS (
                SELECT 1 FROM predictions
                WHERE predictions.batch_id = scan_batches.id
            ) AND created_at < ?
            """,
            (history_cutoff,),
        )
        connection.execute(
            "DELETE FROM account_tokens WHERE expires_at <= ?", (token_cutoff,)
        )
        connection.execute(
            "DELETE FROM users WHERE email_verified = ? AND created_at < ?",
            (False, history_cutoff),
        )
        connection.execute(
            "DELETE FROM rate_limit_buckets WHERE window_started_at < ?",
            (rate_limit_cutoff,),
        )


