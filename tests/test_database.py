import sys
import types

from backend import database


class FakeCursor:
    def fetchone(self):
        return {"id": 41}


class FakeConnection:
    def __init__(self):
        self.statements = []

    def execute(self, query, parameters=()):
        self.statements.append((query, parameters))
        return FakeCursor()

    def commit(self):
        pass

    def rollback(self):
        pass

    def close(self):
        pass


def install_fake_psycopg(monkeypatch, connection):
    psycopg = types.ModuleType("psycopg")
    psycopg.IntegrityError = type("IntegrityError", (Exception,), {})
    psycopg.connect = lambda dsn, row_factory: connection
    rows = types.ModuleType("psycopg.rows")
    rows.dict_row = object()
    monkeypatch.setitem(sys.modules, "psycopg", psycopg)
    monkeypatch.setitem(sys.modules, "psycopg.rows", rows)


def test_postgresql_connection_uses_dict_rows_and_translates_parameters(monkeypatch):
    connection = FakeConnection()
    install_fake_psycopg(monkeypatch, connection)

    with database._connect("postgresql://user:pass@db.example/app") as db:
        db.execute("SELECT ? AS value", ("test",))

    assert connection.statements == [("SELECT %s AS value", ("test",))]


def test_postgresql_schema_and_insert_ids_use_postgresql_syntax(monkeypatch):
    connection = FakeConnection()
    install_fake_psycopg(monkeypatch, connection)
    database_url = "postgresql://user:pass@db.example/app"

    database.init_db(database_url)
    user_id = database.create_user(database_url, "USER@example.org", "long-test-password")

    assert user_id == 41
    statements = [query for query, _ in connection.statements]
    assert any("GENERATED BY DEFAULT AS IDENTITY" in query for query in statements)
    assert all("PRAGMA" not in query for query in statements)
    insert_query, insert_parameters = connection.statements[-1]
    assert "RETURNING id" in insert_query
    assert insert_parameters[0] == "user@example.org"
