def _insert_id(connection, database_url, statement, parameters):
    if is_postgresql_database(database_url):
        cursor = connection.execute(
            f"{statement.rstrip().rstrip(';')} RETURNING id", parameters
        )
        return cursor.fetchone()["id"]
    return connection.execute(statement, parameters).lastrowid


def is_integrity_error(error):
    if isinstance(error, sqlite3.IntegrityError):
        return True
    try:
        import psycopg
    except ImportError:
        return False
    return isinstance(error, psycopg.IntegrityError)


def create_user(database_path, email, password):
    created_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    with _connect(database_path) as connection:
        return _insert_id(
            connection,
            database_path,
            "INSERT INTO users (email, password_hash, created_at, email_verified) "
            "VALUES (?, ?, ?, ?)",
            (email.strip().lower(), generate_password_hash(password), created_at, False),
        )


