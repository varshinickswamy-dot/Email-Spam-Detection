def verify_user(database_path, email, password):
    user = get_user_by_email(database_path, email)
    if user and check_password_hash(user["password_hash"], password):
        return {
            key: user[key]
            for key in ("id", "email", "created_at", "email_verified", "auth_version")
        }
    return None


def store_account_token(database_path, user_id, token_hash, purpose, expires_at):
    created_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    with _connect(database_path) as connection:
        connection.execute(
            "DELETE FROM account_tokens WHERE user_id = ? AND purpose = ?",
            (user_id, purpose),
        )
        connection.execute(
            """
            INSERT INTO account_tokens (token_hash, user_id, purpose, expires_at, created_at)
            VALUES (?, ?, ?, ?, ?)
            """,
            (token_hash, user_id, purpose, expires_at, created_at),
        )


def consume_account_token(database_path, token_hash, purpose, now):
    with _connect(database_path) as connection:
        row = connection.execute(
            """
            DELETE FROM account_tokens
            WHERE token_hash = ? AND purpose = ? AND expires_at > ?
            RETURNING user_id
            """,
            (token_hash, purpose, now),
        ).fetchone()
    return row["user_id"] if row else None


