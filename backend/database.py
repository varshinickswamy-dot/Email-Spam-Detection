def is_postgresql_database(database_url):
    return str(database_url).startswith(("postgres://", "postgresql://"))


class _ConnectionAdapter:
    def __init__(self, connection, postgres):
        self._connection = connection
        self._postgres = postgres

    def execute(self, query, parameters=()):
        if self._postgres:
            query = re.sub(r"\?", "%s", query)
        return self._connection.execute(query, parameters)


@contextmanager
def _connect(database_path):
    postgres = is_postgresql_database(database_path)
    if postgres:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as error:
            raise RuntimeError(
                "PostgreSQL support requires psycopg. Install the project requirements."
            ) from error
        connection = psycopg.connect(database_path, row_factory=dict_row)
    else:
        connection = sqlite3.connect(database_path, timeout=10)
    try:
        if not postgres:
            connection.row_factory = sqlite3.Row
            connection.execute("PRAGMA foreign_keys = ON")
            connection.execute("PRAGMA busy_timeout = 10000")
        yield _ConnectionAdapter(connection, postgres)
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db(database_path):
    postgres = is_postgresql_database(database_path)
    if not postgres:
        Path(database_path).parent.mkdir(parents=True, exist_ok=True)
    with _connect(database_path) as connection:
        if postgres:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    email_verified BOOLEAN NOT NULL DEFAULT TRUE,
                    auth_version INTEGER NOT NULL DEFAULT 0
                )
                """
            )
            connection.execute(
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS "
                "email_verified BOOLEAN NOT NULL DEFAULT TRUE"
            )
            connection.execute(
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS "
                "auth_version INTEGER NOT NULL DEFAULT 0"
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS account_tokens (
                    token_hash TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
                    expires_at TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS rate_limit_buckets (
                    bucket_key TEXT PRIMARY KEY,
                    attempts INTEGER NOT NULL,
                    window_started_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS predictions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    text TEXT NOT NULL,
                    label TEXT NOT NULL CHECK (label IN ('spam', 'not_spam')),
                    confidence REAL NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
                    created_at TEXT NOT NULL,
                    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                    subject TEXT NOT NULL DEFAULT '',
                    sender TEXT NOT NULL DEFAULT '',
                    classification TEXT NOT NULL DEFAULT '',
                    risk_level TEXT NOT NULL DEFAULT 'low',
                    risk_score INTEGER NOT NULL DEFAULT 0,
                    details_json TEXT NOT NULL DEFAULT '{}',
                    batch_id TEXT,
                    scan_kind TEXT NOT NULL DEFAULT 'single'
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS scan_batches (
                    id TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    created_at TEXT NOT NULL,
                    total INTEGER NOT NULL DEFAULT 0
                )
                """
            )
        else:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    email TEXT NOT NULL UNIQUE COLLATE NOCASE,
                    password_hash TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
                """
            )
            user_columns = {
                row["name"] for row in connection.execute("PRAGMA table_info(users)")
            }
